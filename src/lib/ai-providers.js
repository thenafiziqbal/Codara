import "server-only";

const GEMINI_MODEL = "gemini-1.5-flash-latest";
const GROK_MODEL = "grok-2-latest";

const FETCH_TIMEOUT_MS = 60_000;

async function timedFetch(url, opts) {
  const controller = new AbortController();
  const t = setTimeout(() => controller.abort(), FETCH_TIMEOUT_MS);
  try {
    return await fetch(url, { ...opts, signal: controller.signal });
  } finally {
    clearTimeout(t);
  }
}

export class AIProviderError extends Error {
  constructor(message, status = 502) {
    super(message);
    this.status = status;
  }
}

async function callGemini({ system, user }) {
  const key = process.env.GEMINI_API_KEY;
  if (!key) throw new AIProviderError("GEMINI_API_KEY is not configured.", 503);
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${GEMINI_MODEL}:generateContent?key=${encodeURIComponent(key)}`;
  const body = {
    systemInstruction: system ? { role: "system", parts: [{ text: system }] } : undefined,
    contents: [{ role: "user", parts: [{ text: user }] }],
    generationConfig: {
      temperature: 0.3,
      maxOutputTokens: 4096,
      responseMimeType: "text/plain",
    },
    safetySettings: [],
  };
  const res = await timedFetch(url, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    const text = await res.text().catch(() => "");
    throw new AIProviderError(`Gemini error ${res.status}: ${text.slice(0, 200)}`);
  }
  const data = await res.json();
  const text = data?.candidates?.[0]?.content?.parts?.map((p) => p.text).join("") || "";
  return text.trim();
}

async function callGrok({ system, user }) {
  const key = process.env.GROK_API_KEY;
  if (!key) throw new AIProviderError("GROK_API_KEY is not configured.", 503);
  const url = "https://api.x.ai/v1/chat/completions";
  const body = {
    model: GROK_MODEL,
    temperature: 0.3,
    max_tokens: 4096,
    messages: [
      ...(system ? [{ role: "system", content: system }] : []),
      { role: "user", content: user },
    ],
  };
  const res = await timedFetch(url, {
    method: "POST",
    headers: {
      "content-type": "application/json",
      authorization: `Bearer ${key}`,
    },
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    const text = await res.text().catch(() => "");
    throw new AIProviderError(`Grok error ${res.status}: ${text.slice(0, 200)}`);
  }
  const data = await res.json();
  const text = data?.choices?.[0]?.message?.content || "";
  return text.trim();
}

export async function generate({ provider = "gemini", system, user }) {
  if (provider === "grok") return callGrok({ system, user });
  return callGemini({ system, user });
}

export function tryParseJson(text) {
  if (!text) return null;
  // Strip ```json fences if present.
  const stripped = text
    .replace(/^\s*```(?:json)?/i, "")
    .replace(/```\s*$/i, "")
    .trim();
  try {
    return JSON.parse(stripped);
  } catch {
    // Try to extract the first {...} or [...] block.
    const m = stripped.match(/[\[{][\s\S]*[\]}]/);
    if (!m) return null;
    try {
      return JSON.parse(m[0]);
    } catch {
      return null;
    }
  }
}

